/**
 * @openelement/ui — the colour axis of the UTILITY rules (alpha15 S lane).
 *
 * CUSTOMIZATION.md's colour clause covers both authoring forms: "Colours still
 * come from this role table, never from a literal — either a role variable in
 * the sheet or a utility generated from a role (`bg-primary/14` compiles to
 * `color-mix` on `--color-primary`). The guard fails on a raw colour literal in
 * a declaration, because a literal escapes the light, dark and forced-colors
 * seats the roles guarantee."
 *
 * The older guard reads the AUTHORED sources only, so a class attribute saying
 * `bg-red-500` passed it: the token is not a declaration, and the rule it
 * compiles to is generated by the engine, not written by the component. The
 * public variables a utility rule consumes are part of the customization
 * surface all the same — a consumer who re-seats the roles must control them —
 * so this guard decides the whole colour axis from the ENGINE's output for the
 * tokens the components actually carry.
 *
 * How it decides, without a second utility grammar: the components' literal
 * class tokens are admitted into the component-entry shape and compiled by the
 * official engine (`tailwindcss`, the declared devDep). Every colour-bearing
 * declaration the engine generated is then required to resolve to a role the
 * component's own role source declares (`src/theme.css`):
 *
 *   1. a `var(--color-X)` outside the declared roles fails (`bg-red-500` →
 *      `var(--color-red-500)`, `text-violet-700` → `var(--color-violet-700)`);
 *   2. a colour LITERAL — a hex or a colour function — fails, even wrapped in
 *      `color-mix()` (`bg-[#ef4444]`, `bg-[oklch(0.5_0.2_20)]`);
 *   3. a bare palette word fails (`bg-[red]`): the check reads the palette root
 *      names from `tailwindcss/colors`, the engine's own data, rather than
 *      carrying a hand-written colour list. It is not a complete CSS named
 *      colour table — an exotic arbitrary value such as `bg-[rebeccapurple]`
 *      is out of its reach, and deliberately so: the alternative is a
 *      148-entry list pretending to be a grammar.
 */
import { readFile, readdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test } from 'vitest';
import { compile } from 'tailwindcss';
import colors from 'tailwindcss/colors';

const require = createRequire(import.meta.url);
const srcDir = fileURLToPath(new URL('../src', import.meta.url));
const themeSourcePath = join(srcDir, 'theme.css');
const repoRoot = fileURLToPath(new URL('../../..', import.meta.url));
const themeSource = await readFile(themeSourcePath, 'utf8');

/** The role names the component role source declares — the whole colour surface. */
function declaredRoles(css: string): Set<string> {
  const block = /@theme[^{]*\{([\s\S]*?)\n\}/.exec(css)?.[1] ?? '';
  return new Set([...block.matchAll(/(--color-[a-z0-9-]+)\s*:/g)].map((match) => match[1]!));
}

const ROLES = declaredRoles(themeSource);

/** The official engine's stylesheet loader (same shape as the delivery guard). */
async function loadStylesheet(id: string) {
  for (const candidate of [id, `${id}/index.css`]) {
    try {
      const path = require.resolve(candidate);
      if (path.endsWith('.css')) {
        return { path, base: dirname(path), content: await readFile(path, 'utf8') };
      }
    } catch {
      // Try the next spelling.
    }
  }
  throw new Error(`the colour-role guard cannot resolve the stylesheet "${id}"`);
}

/**
 * Compile the component-entry shape for one component: the theme layer, the
 * component's own role source, the utilities layer, and one admitted candidate
 * per literal class token the component's markup carries. Mirrors
 * `renderComponentUtilitiesEntry` (@openelement/router) — whose shape is pinned
 * in that package's `tailwind-entry.test.ts` — so this guard compiles what the
 * build compiles.
 */
async function compileComponentTokens(tokens: readonly string[]): Promise<string> {
  const entry =
    "@import 'tailwindcss/theme.css';\n" +
    `@import '${themeSourcePath}';\n` +
    "@import 'tailwindcss/utilities.css';\n" +
    tokens.map((token) => `@source inline("${token}");`).join('\n') +
    '\n';
  const compiler = await compile(entry, {
    base: repoRoot,
    from: join(repoRoot, '.openElement/utility-colour-roles-guard.css'),
    loadStylesheet,
  });
  return compiler.build([...tokens]);
}

/** Every literal class token a component's markup carries. */
function classTokens(tsx: string): string[] {
  const tokens = new Set<string>();
  for (const match of tsx.matchAll(/\bclass=(?:'([^']*)'|"([^"]*)")/g)) {
    for (const token of (match[1] ?? match[2] ?? '').split(/\s+/)) {
      if (token !== '') tokens.add(token);
    }
  }
  return [...tokens];
}

/** The class hooks a component's own sheet selects — not utility tokens. */
function hookNames(css: string): Set<string> {
  const names = new Set<string>();
  for (const match of css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .matchAll(/\.(-?[A-Za-z_][A-Za-z0-9_-]*)/g)) {
    names.add(match[1]!);
  }
  return names;
}

/** Colour-bearing properties, shorthand forms included. */
const COLOUR_PROPERTY =
  /^(?:color|background|background-color|border|border-(?:top|right|bottom|left)|border-(?:top|right|bottom|left)-color|border-color|outline|outline-color|fill|stroke|box-shadow|text-shadow|text-decoration|text-decoration-color|caret-color|accent-color|-webkit-text-fill-color)$/;

/** Values that carry no colour of their own. */
const COLOUR_KEYWORDS = new Set([
  'transparent',
  'currentcolor',
  'inherit',
  'initial',
  'unset',
  'revert',
  'revert-layer',
  'none',
]);

/** The engine's own palette roots — data, not a grammar. */
const PALETTE_WORDS = new Set([...Object.keys(colors), 'black', 'white']);

const HEX = /#[0-9a-fA-F]{3,8}\b/;
const COLOUR_FUNCTION = /\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color|device-cmyk)\(/i;
const COLOUR_VAR = /var\(\s*(--color-[a-z0-9-]+)/g;

/** One compiled rule: its selector and its declarations. */
interface CompiledRule {
  selector: string;
  declarations: string[];
}

/** The rules of a compiled sheet, custom-property-only blocks skipped. */
function rulesOf(css: string): CompiledRule[] {
  const rules: CompiledRule[] = [];
  const withoutTheme = css.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const chunk of withoutTheme.split('}')) {
    const bodyAt = chunk.lastIndexOf('{');
    if (bodyAt === -1) continue;
    const selector = chunk.slice(0, bodyAt).split('{').pop()!.trim();
    const declarations = chunk
      .slice(bodyAt + 1)
      .split(';')
      .map((declaration) => declaration.trim())
      .filter((declaration) => declaration !== '' && !declaration.startsWith('--'));
    if (selector !== '' && declarations.length > 0) rules.push({ selector, declarations });
  }
  return rules;
}

/**
 * The colour failures one compiled sheet carries: declarations whose colour
 * does not come from the declared roles.
 *
 * One shape is legal and must not be read as a bypass: for a role colour with
 * an alpha modifier the engine writes a progressive-enhancement FALLBACK that
 * inlines the role's resolved value, then overrides it with the role variable
 * inside `@supports (color: color-mix(in lab, red, red))` —
 *
 *   .bg-primary\/14 { background-color: color-mix(in srgb, oklch(49.1% …) 14%, transparent) }
 *   @supports (…) { .bg-primary\/14 { background-color: color-mix(in oklab, var(--color-primary) 14%, transparent) } }
 *
 * so the effective rule on every engine that supports the mix IS the role. The
 * excuse is deliberately narrow: the failing declaration must itself be a
 * `color-mix`, and the SAME selector+property must carry a declared role
 * variable. A palette utility is not excused by it — nothing supplies a role
 * version of `bg-red-500` — which the RED proof below pins.
 */
function colourFailures(css: string): string[] {
  const failures: string[] = [];
  const roleVersions = new Set<string>();
  const rules = rulesOf(css);
  for (const rule of rules) {
    for (const declaration of rule.declarations) {
      const colon = declaration.indexOf(':');
      if (colon === -1) continue;
      const property = declaration.slice(0, colon).trim().toLowerCase();
      if (!COLOUR_PROPERTY.test(property)) continue;
      for (const match of declaration.slice(colon + 1).matchAll(COLOUR_VAR)) {
        if (ROLES.has(match[1]!)) roleVersions.add(`${rule.selector}|${property}`);
      }
    }
  }

  for (const rule of rules) {
    for (const declaration of rule.declarations) {
      const colon = declaration.indexOf(':');
      if (colon === -1) continue;
      const property = declaration.slice(0, colon).trim().toLowerCase();
      if (!COLOUR_PROPERTY.test(property)) continue;
      const value = declaration.slice(colon + 1).trim();
      const lower = value.toLowerCase();

      // 1. A role variable outside the declared table.
      for (const match of value.matchAll(COLOUR_VAR)) {
        if (!ROLES.has(match[1]!)) {
          failures.push(
            `${rule.selector} { ${property}: ${value} } — ${match[1]} is not a declared role`,
          );
        }
      }
      // 2. A colour literal. Role references are removed first, so the
      //    `color-mix(in srgb, var(--color-primary) 14%, transparent)` a role
      //    utility compiles to is not read as a literal.
      const withoutRoles = value.replace(/var\(\s*--color-[a-z0-9-]+\s*\)/g, '');
      const literal = HEX.test(withoutRoles) || COLOUR_FUNCTION.test(withoutRoles);
      if (
        literal &&
        !(lower.includes('color-mix(') && roleVersions.has(`${rule.selector}|${property}`))
      ) {
        failures.push(`${rule.selector} { ${property}: ${value} } — a colour literal`);
        continue;
      }
      // 3. A bare palette word (`bg-[red]`).
      const words = lower
        .replace(/var\([^)]*\)/g, ' ')
        .split(/[^a-z-]+/)
        .filter((word) => word !== '' && !COLOUR_KEYWORDS.has(word));
      const palette = words.find((word) => PALETTE_WORDS.has(word));
      if (palette !== undefined) {
        failures.push(`${rule.selector} { ${property}: ${value} } — the palette word "${palette}"`);
      }
    }
  }
  return failures;
}

const componentFiles = (await readdir(srcDir))
  .filter((name) => name.startsWith('open-') && name.endsWith('.tsx'))
  .sort();

test('the guard has components to check', () => {
  expect(componentFiles.length).toBeGreaterThan(0);
  expect(ROLES.size).toBeGreaterThan(0);
});

for (const file of componentFiles) {
  test(`${file}: every generated colour resolves to a declared role`, async () => {
    const tag = file.replace(/\.tsx$/, '');
    const tsx = await readFile(join(srcDir, file), 'utf8');
    const hooks = hookNames(await readFile(join(srcDir, `${tag}.css`), 'utf8'));
    // The hooks are the component's own sheet's business (guarded separately);
    // this guard decides the tokens the ENGINE compiles.
    const tokens = classTokens(tsx).filter((token) => !hooks.has(token));
    expect(tokens.length, `${tag} must carry utility tokens`).toBeGreaterThan(0);
    const css = await compileComponentTokens(tokens);
    expect(
      colourFailures(css),
      `${tag}: a utility the component authors must generate its colour from the role table`,
    ).toEqual([]);
  });
}

test('the guard would catch a palette utility, an arbitrary value and a palette word', async () => {
  // The RED proof for this guard, on the guard's own compile path: the three
  // bypass shapes CUSTOMIZATION.md's colour clause is meant to stop. Without
  // this, a guard that silently matched nothing would look green.
  const css = await compileComponentTokens([
    'bg-red-500',
    'bg-[#ef4444]',
    'text-[oklch(0.5_0.2_20)]',
    'bg-[red]',
    'bg-primary',
  ]);
  const failures = colourFailures(css).join('\n');
  expect(failures, 'a palette step utility').toContain('--color-red-500 is not a declared role');
  expect(failures, 'a hex literal').toContain('a colour literal');
  expect(failures, 'an arbitrary colour function').toContain('a colour literal');
  expect(failures, 'a bare palette word').toContain('the palette word "red"');
  // …and the role-generated utility is not a failure.
  expect(failures, 'a role utility must stay legal').not.toContain('--color-primary');
});

test('a role utility with an alpha modifier stays legal through its engine fallback', async () => {
  // The engine's own progressive-enhancement shape: an inlined-value fallback
  // overridden by the role variable under `@supports`. If this ever stopped
  // being excused the guard would fail on shipped components; if the excuse
  // were widened to any literal, the RED proof above would still pass — so both
  // directions are pinned here.
  const css = await compileComponentTokens([
    'bg-primary/14',
    'hover:bg-primary/23',
    'text-foreground',
  ]);
  expect(css, 'the engine must ship the role version').toContain(
    'color-mix(in oklab, var(--color-primary) 14%, transparent)',
  );
  expect(colourFailures(css), 'the role utility must not be read as a bypass').toEqual([]);
});
