/**
 * Generate the site data modules required by tests, the site check tools and the
 * site build on a clean clone.
 *
 * One canonical entry for every committed site content module, emitted from
 * the checked-in inputs (verified with a single --check):
 *   www/content/**                      -> _generated-{guide,architecture,blog}-data.ts
 *   CHANGELOG.md                        -> _generated-changelog-archive.ts
 *   docs/release/release-state.json     -> _generated-release-line.ts
 *   www/lib/content-dates.json          -> _generated-content-meta.ts
 *   PAGE_CODE_SOURCES (below)           -> _generated-page-code.ts
 *
 * The remaining modules under www/app/data/ (_generated-api-reference.ts,
 * version.ts) are consumed as ordinary checked-in modules; the API reference
 * has its own `pnpm --filter @openelement/www run generate:api-reference` gate.
 *
 * `--check` regenerates in memory and fails on drift.
 */
import {
  loadCollectionData,
  writeBlogDataModule,
  writeCollectionDataModule,
} from '../lib/content.ts';
import { highlightSiteCode, renderSiteMarkdown } from '../lib/markdown.ts';
import { quickstartCommandCount } from '../lib/quickstart.ts';
import { blogCollection, prepareBlogPosts } from '../lib/blog.ts';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { articleCollections } from '../content-collections.ts';
import { readFile, writeFile } from 'node:fs/promises';
import process from 'node:process';

const siteRoot = fileURLToPath(new URL('../../www/', import.meta.url));

/**
 * The two page-component code blocks (home hero, contributing setup) — the
 * one copy of their source. They live here, not in the JSX, because the
 * highlighted markup is compiled at generation time through the site's ONE
 * highlight pipeline (lib/markdown.ts) and projected into <open-code-block>
 * as trusted HTML; the pages carry only the generated bytes. Editing a
 * snippet means editing here and rerunning generate:content (check:content-data
 * fails on drift).
 */
const PAGE_CODE_SOURCES = {
  homeHeroCode: {
    lang: 'tsx',
    source: `import { element, OpenElement, property } from '@openelement/element'

@element('open-counter', { root: 'shadow-open' })
export class OpenCounter extends OpenElement {
  @property({ reflect: true, attribute: 'count', type: Number })
  count = 0

  render() {
    return (
      <button type="button">Count: {this.count}</button>
    )
  }
}

// SSR: <open-counter count="0"> + DSD shadow root.
// Markup paints and reads with no JavaScript.`,
  },
  contributingSetupCode: {
    lang: 'bash',
    source: `git clone https://github.com/open-element/openelement.git
cd openelement
pnpm install
pnpm test`,
  },
} as const;

const outputs = new Map<string, string>();
for (const name of ['guide', 'architecture'] as const) {
  const options = {
    ...articleCollections[name],
    contentDir: join(siteRoot, articleCollections[name].contentDir),
  };
  // The loader resolves the site's computed placeholders ({{INSTALL_COMMAND}}
  // among them, #1414) before rendering, so the emitted module already carries
  // the create CLI's canonical string.
  const entries = await loadCollectionData(name, options);
  const output = writeCollectionDataModule(name, entries, options);
  outputs.set(join(siteRoot, `app/data/_generated-${name}-data.ts`), output);
}

const blogOptions = { ...blogCollection, contentDir: join(siteRoot, blogCollection.contentDir) };
const blogEntries = await loadCollectionData('blog', blogOptions);
outputs.set(
  join(siteRoot, 'app/data/_generated-blog-data.ts'),
  writeBlogDataModule(prepareBlogPosts(blogEntries)),
);

// Changelog archive, rendered from the repository CHANGELOG.md (a first-party
// file — same trust level as the collections) through the same build-time
// markdown pipeline, so its fences carry identical build-time highlighting.
// The route consumes this module instead of reading the filesystem and
// running marked at render time: a missing CHANGELOG.md now fails the
// generation step itself (fail closed) rather than shipping a fallback page.
const changelogSource = await readFile(join(siteRoot, '../CHANGELOG.md'), 'utf8');
// CHANGELOG.md links are repository-relative so they resolve on GitHub; on
// the built site they would 404 (#1159 link truth), so they are projected
// onto the canonical GitHub tree before rendering.
const changelogMarkdown = changelogSource
  .replace(/^#\s+Changelog\s*\n/, '')
  .replaceAll('](./', '](https://github.com/open-element/openelement/tree/main/');
outputs.set(
  join(siteRoot, 'app/data/_generated-changelog-archive.ts'),
  `// GENERATED by www/tools/generate-site-content-data.ts from the repository
// CHANGELOG.md — do not edit by hand. Regenerate with
// \`pnpm --filter @openelement/www run generate:content\` (part of site:build).

/** Rendered CHANGELOG.md archive: H1 stripped, links projected, fences highlighted. */
export const changelogArchiveHtml: string = ${JSON.stringify(await renderSiteMarkdown(changelogMarkdown))};
`,
);

// The two page-component code blocks, pre-highlighted through the same Shiki
// pipeline as every fence (single highlighter instance, single --shiki-*
// theme; sources live in PAGE_CODE_SOURCES above). The routes project these
// bytes into <open-code-block> as trusted HTML.
outputs.set(
  join(siteRoot, 'app/data/_generated-page-code.ts'),
  `// GENERATED by www/tools/generate-site-content-data.ts from PAGE_CODE_SOURCES
// in that tool — do not edit by hand. Regenerate with
// \`pnpm --filter @openelement/www run generate:content\` (part of site:build).

/** Home hero: the open-counter component example, Shiki-highlighted (tsx). */
export const homeHeroCodeHtml: string = ${JSON.stringify(
    await highlightSiteCode(
      PAGE_CODE_SOURCES.homeHeroCode.source,
      PAGE_CODE_SOURCES.homeHeroCode.lang,
    ),
  )};

/** Contributing setup: the clone/build command sequence, Shiki-highlighted (bash). */
export const contributingSetupCodeHtml: string = ${JSON.stringify(
    await highlightSiteCode(
      PAGE_CODE_SOURCES.contributingSetupCode.source,
      PAGE_CODE_SOURCES.contributingSetupCode.lang,
    ),
  )};
`,
);

// Release-line truth, derived from docs/release/release-state.json (the
// registry-verified source of truth) so site copy about the source line
// flips automatically when the release train publishes — no manual wording
// sweep. Consumed by www/app/data/version.ts and, for the changelog
// register's decided presentation, by www/app/routes/changelog.tsx.
const releaseState = JSON.parse(
  await readFile(join(siteRoot, '../docs/release/release-state.json'), 'utf8'),
) as {
  sourceVersion: string;
  packages: Array<{
    name: string;
    status?: 'published' | 'unpublished';
    registry?: Record<string, string | undefined>;
  }>;
  latestPrerelease?: { version?: string };
  commonCompleteVersion?: string | null;
};
const sourceVersion = releaseState.sourceVersion;
// Schema v4 (#1557): only published packages carry dist-tags; an unpublished
// package has no @alpha tag and cannot vote on the published claim.
const publishedPackages = releaseState.packages.filter((pkg) => pkg.status !== 'unpublished');
const alphaResolutions = publishedPackages.map((pkg) => pkg.registry?.alpha);
// The source line counts as published only when EVERY published package's
// @alpha dist-tag resolves to it — a partial train must still read as
// unpublished.
const sourceLinePublished = alphaResolutions.every((v) => v === sourceVersion);
const createEntry = publishedPackages.find((pkg) => pkg.name === '@openelement/create');
const alphaResolvesTo = createEntry?.registry?.alpha ?? 'unknown';

// Stable-line history: the newest STABLE (non-prerelease) version the
// repository CHANGELOG.md records, plus the maintenance series it closes.
// release-state.json tracks registry dist-tags only and carries no 0.x entry,
// so the changelog is the record that owns this fact; the roadmap's
// stable-line sentence derives the number here instead of hand-writing it.
// Fail closed: a release record without a stable heading must break the build,
// never ship a roadmap with a stale stable-line claim.
const stableVersions = [...changelogSource.matchAll(/^##\s+(.+)$/gmu)]
  .flatMap((heading) => heading[1]!.split('/'))
  .map((version) => version.trim())
  .filter((version) => /^\d+\.\d+\.\d+$/u.test(version))
  .sort((left, right) => {
    const a = left.split('.').map(Number);
    const b = right.split('.').map(Number);
    return b[0]! - a[0]! || b[1]! - a[1]! || b[2]! - a[2]!;
  });
const stableLineVersion = stableVersions[0];
if (stableLineVersion === undefined) {
  throw new Error(
    'generate-site-content-data: CHANGELOG.md records no stable (non-prerelease) ' +
      'version — the roadmap stable-line sentence cannot be derived.',
  );
}
const stableLineSeries = `${stableLineVersion.split('.').slice(0, 2).join('.')}.x`;

// The one prerelease version every published package serves on `latest`
// (release-state `latestPrerelease`), cross-checked against the per-package
// `latest` blocks: a sentence naming the current 1.0 alpha line must read one
// version, and a partial or stale record must fail the build instead of
// printing a version the registry does not serve.
const latestPrereleaseVersion = releaseState.latestPrerelease?.version;
if (latestPrereleaseVersion === undefined || !latestPrereleaseVersion.includes('-')) {
  throw new Error(
    'generate-site-content-data: docs/release/release-state.json carries no ' +
      'latestPrerelease.version — the current alpha line cannot be derived.',
  );
}
const sharedLatest = [...new Set(publishedPackages.map((pkg) => pkg.registry?.latest))];
if (sharedLatest.length !== 1 || sharedLatest[0] !== latestPrereleaseVersion) {
  throw new Error(
    'generate-site-content-data: release-state per-package `latest` values ' +
      `(${sharedLatest.join(', ') || 'none'}) disagree with latestPrerelease.version ` +
      `(${latestPrereleaseVersion}) — the alpha-line sentence cannot name one version.`,
  );
}

// The changelog register's presentation is DECIDED here from the tracked
// truth (FRM-06 / CodeQL #4241). The route must not branch on the
// hand-maintained COMMON_PUBLISHED_VERSION mirror in www/app/data/version.ts:
// that constant is a literal null in the checked-in source, so a future-state
// branch on it is statically dead and the analyzer correctly reports a trivial
// conditional. Deciding the label and copy at generation time removes the
// branch while keeping the page's semantics identical: a common stable version
// wins when release:registry-check admits one, otherwise the register names the
// shared prerelease line. The former no-shared-line copy ("none" / "values
// differ") was already unreachable: the per-package `latest` guard above fails
// generation unless every published package serves the one
// latestPrerelease.version, so a divergent or empty registry block never
// reaches a page. `commonCompleteVersion` is the typed string|null contract;
// a non-null value must be present in every published package's tracked
// registry block, so generation fails closed rather than naming a version the
// record cannot prove.
const commonCompleteVersion = releaseState.commonCompleteVersion ?? null;
if (commonCompleteVersion !== null) {
  if (
    typeof commonCompleteVersion !== 'string' ||
    !/^\d+\.\d+\.\d+$/u.test(commonCompleteVersion)
  ) {
    throw new Error(
      'generate-site-content-data: docs/release/release-state.json ' +
        `commonCompleteVersion must be a stable x.y.z or null (got ${JSON.stringify(commonCompleteVersion)}).`,
    );
  }
  for (const pkg of publishedPackages) {
    const versions = Object.values(pkg.registry ?? {}).filter(
      (value): value is string => typeof value === 'string',
    );
    if (!versions.includes(commonCompleteVersion)) {
      throw new Error(
        `generate-site-content-data: commonCompleteVersion ${commonCompleteVersion} is absent ` +
          `from ${pkg.name}'s registry block — the register cannot name it.`,
      );
    }
  }
}
const sharedLatestBare = (sharedLatest[0] ?? '').replace(/^v/u, '');
const registerVersionLabel = commonCompleteVersion ?? sharedLatestBare;
const registerCurrentStamp =
  commonCompleteVersion === null
    ? { en: 'Per-package latest', zh: '各包 latest' }
    : { en: 'Current', zh: '当前' };
const registerCurrentSummary =
  commonCompleteVersion === null
    ? {
        en: `1.0 alpha line: every published package’s npm latest is the same prerelease, ${sharedLatestBare}. No common stable version is published.`,
        zh: `1.0 alpha 线：各发布包的 npm latest 同为预发布版本 ${sharedLatestBare}；不存在共同 stable 版本。`,
      }
    : {
        en: `Every published package serves the common stable version ${commonCompleteVersion}.`,
        zh: `全部发布包都已提供共同稳定版本 ${commonCompleteVersion}。`,
      };

// Roadmap publish-state drift guard: app/routes/roadmap.tsx must not
// hand-write an alpha-train publish claim beside
// docs/release/release-state.json — that status is derived in
// www/app/data/version.ts from the same generated truth, so whichever claim
// contradicts the tracked registry state fails here and turns CI red
// (www#check:content-data) instead of shipping a stale roadmap row.
const roadmapSource = await readFile(join(siteRoot, 'app/routes/roadmap.tsx'), 'utf8');
const contradictingClaims = sourceLinePublished
  ? [/repository baseline/iu, /not yet on npm/iu, /仓库基线——尚未发布到 npm/u]
  : [/published to npm under the @alpha dist-tag/iu, /已通过 @alpha dist-tag 发布到 npm/u];
const roadmapDrift = contradictingClaims.filter((claim) => claim.test(roadmapSource));
if (roadmapDrift.length > 0) {
  console.error(
    'roadmap publish-state drift: app/routes/roadmap.tsx hand-writes an alpha-train ' +
      'publish claim that contradicts docs/release/release-state.json; the status ' +
      'must stay derived from www/app/data/version.ts.',
  );
  for (const claim of roadmapDrift) console.error(`  ${claim}`);
  process.exit(1);
}

outputs.set(
  join(siteRoot, 'app/data/_generated-release-line.ts'),
  `// GENERATED by www/tools/generate-site-content-data.ts from
// docs/release/release-state.json — do not edit by hand. Regenerate with
// \`pnpm --filter @openelement/www run generate:content\` (part of site:build).
export const SOURCE_VERSION = '${sourceVersion}';
export const SOURCE_LINE_PUBLISHED = ${sourceLinePublished};
export const ALPHA_RESOLVES_TO = '${alphaResolvesTo}';
/** release-state packages[] length: the published consumer surface size. */
export const PACKAGE_COUNT = ${releaseState.packages.length};
/** Newest STABLE version recorded in CHANGELOG.md (stable-line history). */
export const STABLE_LINE_VERSION = '${stableLineVersion}';
/** The maintenance series STABLE_LINE_VERSION belongs to (e.g. "0.43.x"). */
export const STABLE_LINE_SERIES = '${stableLineSeries}';
/** The prerelease every published package serves on \`latest\` (registry truth). */
export const LATEST_PRERELEASE_VERSION = '${latestPrereleaseVersion}';
/** release-state commonCompleteVersion: newest STABLE version published for every package, or null. */
export const COMMON_COMPLETE_VERSION: string | null = ${JSON.stringify(commonCompleteVersion)};
/** The changelog register's headline label, decided at generation time (FRM-06 / #4241). */
export const REGISTER_VERSION_LABEL = '${registerVersionLabel}';
/** The register's current-state stamp, per page locale, decided at generation time. */
export const REGISTER_CURRENT_STAMP: Readonly<Record<'en' | 'zh', string>> = ${JSON.stringify(registerCurrentStamp)};
/** The register's current-state summary, per page locale, decided at generation time. */
export const REGISTER_CURRENT_SUMMARY: Readonly<Record<'en' | 'zh', string>> = ${JSON.stringify(registerCurrentSummary)};
`,
);

// Quickstart count: parsed from getting-started's authored Install fence
// (www/lib/quickstart.ts) — the same parse the `{{QUICKSTART_COMMAND_COUNT}}`
// placeholder resolves through, so the hub route's build-time constant and the
// guides' interpolated number can never disagree. The steps themselves are
// never copied here: one authored sequence, one derived count.
const quickstartCount = quickstartCommandCount();
outputs.set(
  join(siteRoot, 'app/data/_generated-quickstart.ts'),
  `// GENERATED by www/tools/generate-site-content-data.ts from the Install fence
// in www/content/docs/guide/getting-started.md — do not edit by hand.
// Regenerate with \`pnpm --filter @openelement/www run generate:content\` (part
// of site:build).
/** Commands the documented quickstart runs (the fence's step count). */
export const QUICKSTART_COMMAND_COUNT = ${quickstartCount};
`,
);

// Per-article source-freshness stamps, projected from the committed
// manifest (never from Git: the build must run without .git or a network).
const contentDates = JSON.parse(
  await readFile(join(siteRoot, 'lib/content-dates.json'), 'utf8'),
) as { generatedFrom: string; articles: Record<string, { en: string; zh: string }> };
const STAMP = /^(?:\d{4}-\d{2}-\d{2}|uncommitted)$/;
const metaMap: Record<string, { en: string; zh: string }> = {};
for (const slug of Object.keys(contentDates.articles).sort()) {
  const stamps = contentDates.articles[slug];
  if (!STAMP.test(stamps.en) || !STAMP.test(stamps.zh)) {
    throw new Error(`generate-site-content-data: bad date stamps for ${slug}`);
  }
  metaMap[slug] = { en: stamps.en, zh: stamps.zh };
}
outputs.set(
  join(siteRoot, 'app/data/_generated-content-meta.ts'),
  `// Auto-generated by www/tools/generate-site-content-data.ts from lib/content-dates.json - do not edit.

/** Last-commit ISO date per article source, keyed by \`<collection>/<slug>\`. */
export const contentMeta: Record<string, { en: string; zh: string }> = ${JSON.stringify(
    metaMap,
    null,
    2,
  )};
`,
);

if (process.argv.slice(2).includes('--check')) {
  const drifted: string[] = [];
  for (const [path, expected] of outputs) {
    let current = '';
    try {
      current = await readFile(path, 'utf8');
    } catch {
      // Missing file is drift; fall through to the mismatch path.
    }
    if (current !== expected) drifted.push(path);
  }
  if (drifted.length > 0) {
    console.error(
      'site content data drift: regenerate with pnpm --filter @openelement/www run generate:content',
    );
    for (const path of drifted) console.error(`  ${path}`);
    process.exit(1);
  }
  console.log('site content data check passed.');
} else {
  for (const [path, output] of outputs) await writeFile(path, output);
  console.log(`site content data written: ${outputs.size} modules.`);
}
